"""The thunderstorm flash the consoles play, computed from the source overlay.

thunderstormoverlay.cpp draws a white quad whose alpha is fbm(time) * 3, faded in over 0.2 s while
lightning lasts (3 s) and faded out over 0.2 s while silence lasts (5 s). The noise uses float sines,
so the consoles play one precomputed cycle: silence first, then lightning, at 60 ticks per second,
as levels 0 (no flash) to LEVELS. A strike starts lightning at full strength.

    python tools/thunderstorm_curve.py   # rewrites src/game/thunderstormcurve.h
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'src/game/thunderstormcurve.h'
TICKS_PER_SECOND = 60
LIGHTNING_S, SILENCE_S, FADE_PER_S = 3.0, 5.0, 5.0
LEVELS = 16


def fract(x):
    return x - math.floor(x)


def hash2(x, y):
    return fract(1e4 * math.sin(17.0 * x + y * 0.1) * (0.1 + abs(math.sin(y * 13.0 + x))))


def noise2(x, y):
    ix, iy, fx, fy = math.floor(x), math.floor(y), fract(x), fract(y)
    a, b, c, d = hash2(ix, iy), hash2(ix + 1, iy), hash2(ix, iy + 1), hash2(ix + 1, iy + 1)
    ux, uy = fx * fx * (3 - 2 * fx), fy * fy * (3 - 2 * fy)
    return a * (1 - ux) + b * ux + (c - a) * uy * (1 - ux) + (d - b) * ux * uy


def fbm(x, y=0.0):
    value, amplitude = 0.0, 0.5
    for _ in range(6):
        value += amplitude * noise2(x, y)
        x, y, amplitude = x * 2, y * 2, amplitude * .5
    return value


def curve():
    """Levels for one silence-then-lightning cycle, and the tick lightning starts at."""
    dt = 1.0 / TICKS_PER_SECOND
    silence, lightning = round(SILENCE_S * TICKS_PER_SECOND), round(LIGHTNING_S * TICKS_PER_SECOND)
    levels, factor, time_s = [], 1.0, 0.0
    for tick in range(silence + lightning):
        time_s += dt
        if tick < silence:
            factor = max(factor - dt * FADE_PER_S, 0.0)
        else:
            factor = min(factor + dt * FADE_PER_S, 1.0)
        # static_cast<uint8_t>(value * 255) is not clamped: on x86 builds values above 1 wrap around, which is
        # what makes its flash flicker instead of holding white.
        alpha = int(fbm(time_s) * 3.0 * factor * 255) & 255
        levels.append(round(alpha * LEVELS / 255))
    return levels, silence


def header(levels, lightning_start):
    rows = [', '.join(str(level) for level in levels[index:index + 24]) for index in range(0, len(levels), 24)]
    return '\n'.join([
        '/* generated by tools/thunderstorm_curve.py from thunderstormoverlay.cpp; do not edit. */',
        '#ifndef THUNDERSTORM_CURVE_H', '#define THUNDERSTORM_CURVE_H',
        f'#define THUNDERSTORM_CURVE_TICKS {len(levels)}',
        f'#define THUNDERSTORM_LIGHTNING_START {lightning_start}',
        f'#define THUNDERSTORM_LEVELS {LEVELS}',
        'static const DeceptusU8 thunderstorm_curve[THUNDERSTORM_CURVE_TICKS] = {',
        ',\n'.join('   ' + row for row in rows), '};', '#endif', ''])


if __name__ == '__main__':
    levels, start = curve()
    OUTPUT.write_text(header(levels, start))
    print(len(levels), 'ticks;', sum(1 for level in levels if level), 'lit; peak', max(levels))
