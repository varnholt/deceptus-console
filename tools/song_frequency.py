"""The table behind songFrequency: XM's linear frequencies, 8363 * 2^(step / 768) Hz for one octave of
768 steps, in 1/256 Hz.

    python tools/song_frequency.py   # rewrites src/audio/songfrequencies.h
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'src/audio/songfrequencies.h'
STEPS = 768
MIDDLE_C = 8363
SHIFT = 8


def table():
    return [round(MIDDLE_C * 2 ** (step / STEPS) * (1 << SHIFT)) for step in range(STEPS)]


def header(values):
    rows = [', '.join(str(value) for value in values[index:index + 8]) for index in range(0, len(values), 8)]
    return '\n'.join([
        '/* generated by tools/song_frequency.py; do not edit. */',
        '#ifndef SONG_FREQUENCIES_H', '#define SONG_FREQUENCIES_H',
        f'#define SONG_OCTAVE_STEPS {STEPS}',
        'static const DeceptusU32 song_frequencies[SONG_OCTAVE_STEPS] = {',
        ',\n'.join('   ' + row for row in rows), '};', '#endif', ''])


if __name__ == '__main__':
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(header(table()))
