"""The tracked music the consoles play in place of the original's recorded tracks.

Writes assets/generated/music/songs.c and songs.h: one Song per module in TRACKS, and the song each
original track maps to. assets/music/README.md lists the modules' sources and licenses.

    python tools/music_assets.py
"""
import re
from pathlib import Path

import song_assets

ROOT = Path(__file__).resolve().parents[1]
MODULES = ROOT / 'assets/music'
OUTPUT = ROOT / 'assets/generated/music'
# original track -> module. one module stands in for all of them until the final choice.
TRACKS = {
    'level_test_track_muffler_awakening': 'drozerix_-_chemical_16.xm',
    'level_test_track_muffler_ancestors': 'drozerix_-_chemical_16.xm',
    'menu_test_track_muffler_callisto': 'drozerix_-_chemical_16.xm',
}
# the Amiga plays a song on Paula's four hardware channels, and four voices keep the GBA's software
# mixer at a few percent of a frame: every console song has at most four channels.
CHANNELS = 4


def song_name(module):
    return 'song_' + re.sub('_+', '_', ''.join(character if character.isalnum() else '_' for character in Path(module).stem.lower())).strip('_')


def compile_music(output=OUTPUT, sample_attribute=''):
    output.mkdir(parents=True, exist_ok=True)
    modules = sorted(set(TRACKS.values()))
    source = ['/* generated by tools/music_assets.py; do not edit. */', '#include "songs.h"']
    report = {}
    for module in modules:
        song = song_assets.parse_xm((MODULES / module).read_bytes())
        if song['channels'] > CHANNELS:
            raise song_assets.SongError(f'{module}: {song["channels"]} channels; console songs have at most {CHANNELS}')
        source += song_assets.song_source(song, song_name(module), sample_attribute)
        report[module] = dict(channels=song['channels'], sample_bytes=song_assets.sample_bytes(song))
    header = ['/* generated by tools/music_assets.py; do not edit. */', '#ifndef SONGS_H', '#define SONGS_H',
              '#include "deceptus/song.h"']
    header += [f'extern const Song {song_name(module)};' for module in modules]
    header += [f'#define SONG_{track.upper()} (&{song_name(module)})' for track, module in TRACKS.items()]
    header += ['#endif', '']
    (output / 'songs.c').write_text('\n'.join(source) + '\n')
    (output / 'songs.h').write_text('\n'.join(header))
    return report


if __name__ == '__main__':
    for module, details in compile_music().items():
        print(module, details)
